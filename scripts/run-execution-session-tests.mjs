import { createServer } from 'vite'
import assert from 'node:assert/strict'
const server = await createServer({ appType: 'custom', logLevel: 'error', server: { middlewareMode: true } })
try {
  const { useSimulationStore: store } = await server.ssrLoadModule('/src/store/simulationStore.ts')
  const s = () => store.getState()
  const first = s().beginExecution('project-a', 'ARDUINO_UNO', 'source-a')
  assert(first)
  assert.equal(s().beginExecution('project-a', 'ARDUINO_UNO', 'duplicate'), null)
  s().transitionExecution(first, 'compiling')
  assert.equal(s().isSimulating, false)
  s().transitionExecution(first, 'compilation-failed', 'missing semicolon')
  assert.equal(s().execution.diagnostic, 'missing semicolon')
  const second = s().beginExecution('project-a', 'ARDUINO_UNO', 'source-b')
  assert.notEqual(first, second)
  s().transitionExecution(first, 'running')
  s().writeSerial('stale output', { runId: first, kind: 'output' })
  assert.equal(s().execution.phase, 'preparing'); assert.deepEqual(s().serialLogs, [])
  s().transitionExecution(second, 'starting'); s().transitionExecution(second, 'running')
  s().setBaudRate(115200)
  s().writeSerial('hel', { runId: second, kind: 'output', newline: false })
  s().writeSerial('lo', { runId: second, kind: 'output' })
  assert.deepEqual(s().serialLogs, ['hello']); assert.equal(s().serialEntries[0].runId, second)
  s().setSerialPanelOpen(false); s().writeSerial('next', { kind: 'output', runId: second })
  assert.equal(s().serialPanelOpen, false, 'New output respects the collapsed panel')
  s().clearSerial(); s().writeSerial('fresh', { kind: 'output', runId: second })
  assert.deepEqual(s().serialLogs, ['fresh']); assert.equal(s().baudRate, 115200)
  s().sendSerialInput('command'); assert.deepEqual(s().drainSerialInput(), ['command'])
  s().transitionExecution(second, 'stopped'); s().sendSerialInput('stopped input')
  assert.deepEqual(s().serialInputQueue, []); assert.equal(s().serialLogs.at(-1), '> command')
  const third = s().beginExecution('project-b', 'ARDUINO_NANO', 'source-c')
  assert.notEqual(second, third); assert.equal(s().execution.projectId, 'project-b')
  assert.deepEqual(s().serialEntries, []); assert.deepEqual(s().serialInputQueue, [])
  for (let i = 0; i < 400; i++) s().writeSerial(String(i), { kind: 'output', runId: third })
  assert.equal(s().serialEntries.length, 300); assert.equal(s().serialLogs.length, 300)
  assert.equal(s().serialLogs[0], '100')
  s().resetExecution(); assert.equal(s().execution.phase, 'idle'); assert.equal(s().isSimulating, false)
  console.log('PASS execution transitions, duplicate initialization, failed compilation, stale run rejection, serial byte assembly, baud, clear, bounded logs, collapse, input gating and project/run isolation')
} finally { await server.close() }
