const makeComponent = (
  component: Omit<ElectronicComponent, 'createdAt' | 'isPremium' | 'sortOrder'> & { sortOrder?: number }
): ElectronicComponent => ({
  createdAt: '',
  isPremium: false,
  sortOrder: component.sortOrder ?? 50,
  ...component,
});

