const builtinByType = new Map(builtinCanvasComponents.map((component) => [component.type, component]));

export function findCatalogComponent(type: string): ElectronicComponent | undefined {
  return builtinByType.get(type);
}

export function mergeComponentLibrary(apiComponents: ElectronicComponent[] = []): ElectronicComponent[] {
  const byType = new Map<string, ElectronicComponent>();
  builtinCanvasComponents.forEach((component) => byType.set(component.type, component));
  apiComponents.forEach((component) => byType.set(component.type, component));
  return Array.from(byType.values());
}
